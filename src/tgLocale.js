export const isInterfaceLanguage = code => INTERFACE_LANGUAGES.some(l=>l.code===code);
export const interfaceDirection = code => INTERFACE_LANGUAGES.find(l=>l.code===code)?.rtl ? 'rtl' : 'ltr';
export const translate = (code,key,params={}) => Object.entries(params).reduce((s,[name,value])=>s.replaceAll('{'+name+'}',String(value)),DICTIONARIES[code]?.[key] || key);
